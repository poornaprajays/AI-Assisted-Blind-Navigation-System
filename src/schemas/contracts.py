"""
VisionMate AI - Foundational Schema Contracts Module
Path: src/schemas/contracts.py

This module defines the standardized runtime data contracts used across the entire 
real-time assistive AI pipeline. To ensure the highest throughput and lowest latency 
on the real-time processing thread, all objects are constructed using Python's 
native dataclasses optimized with __slots__.

================================================================================
WHY __slots__ MATTERS FOR REAL-TIME COMPUTER VISION SYSTEMS:
================================================================================
1. Elimination of __dict__ Overhead:
   Normally, Python objects store their instance variables in a dynamic dictionary 
   (__dict__). This allows adding arbitrary attributes at runtime but introduces a 
   substantial memory footprint per object. In a 30+ FPS assistive CV system, 
   instantiating hundreds of bounding boxes, spatial analytics, and event nodes 
   every second leads to high memory churning. __slots__ dictates that instances 
   store attributes in a static array-like structure, drastically reducing memory usage.

2. Prevention of Garbage Collector Churn:
   Frequent allocation and deallocation of dynamic dictionaries on the hot-path 
   triggers frequent Python Garbage Collector (GC) runs. These small, non-deterministic 
   GC pauses can introduce micro-stutters, causing video frame drops. By using static 
   __slots__, GC overhead is virtually eliminated.

3. Accelerated Attribute Access:
   Accessing slot-based attributes is implemented in CPython as a direct array-offset 
   lookup in C, which is approximately 20-30% faster than looking up keys in a hash map 
   (__dict__).

================================================================================
WHY NORMALIZED SCHEMAS IMPROVE MAINTAINABILITY AND INTEROPERABILITY:
================================================================================
1. Clear Interface Boundaries:
   Standardized contracts decouple the core vision system. The Camera module produces 
   raw frames; the Detection module converts raw model inferences into 'Detection' instances; 
   the Logic module converts detections into 'HazardEvent' contracts; the Audio module speaks 
   'AudioSpeechRequest' specifications. If you swap the AI model (e.g. YOLOv8 for YOLOv10 
   or ONNX) or change the Audio framework, only the adapter translation layer changes.

2. Prevention of Magic Tuple / Dict Bugs:
   Relying on arbitrary dicts (e.g., d["bbox"]) or index arrays (e.g., det[0]) leads to 
   brittle code and silent bugs when coordinate formats change. Named schemas force strict, 
   type-checked contracts, enabling static analysers (Pyright/MyPy) to catch errors before runtime.
"""

from dataclasses import dataclass, field, asdict
from typing import Tuple, Optional
import time
import json


@dataclass(slots=True)
class Detection:
    """
    Standardized schema representing a single detected object in a camera frame.
    This acts as the data contract between the Detection module and the Spatial Logic module.
    
    Fields:
        class_name: The name of the detected object class (e.g., 'chair', 'vehicle', 'door').
        confidence: Model prediction confidence score from 0.0 to 1.0.
        bbox: Absolute pixel coordinates of the bounding box as (xmin, ymin, xmax, ymax).
        center_x: Pre-calculated horizontal center pixel of the bounding box.
        center_y: Pre-calculated vertical center pixel of the bounding box.
        width: Calculated width of the bounding box in pixels.
        height: Calculated height of the bounding box in pixels.
        estimated_distance: Mathematically estimated depth distance from the user in meters.
        spatial_zone: Classified horizontal region of the frame ('left', 'center', 'right').
        timestamp: The epoch timestamp when the video frame was originally captured.
    """
    class_name: str
    confidence: float
    bbox: Tuple[int, int, int, int]
    center_x: int
    center_y: int
    width: int
    height: int
    estimated_distance: float
    spatial_zone: str
    timestamp: float

    def to_dict(self) -> dict:
        """
        Converts the Detection dataclass instance into a clean Python dictionary.
        This provides a standardized format for serialization.
        """
        return asdict(self)

    def to_json(self) -> str:
        """
        Serializes the Detection object to a compact, standard JSON string.
        Perfect for WebSocket streaming, API responses, or writing telemetry logs.
        """
        return json.dumps(self.to_dict())


@dataclass(slots=True)
class HazardEvent:
    """
    Structured event contract generated by the Spatial Logic engine to represent
    active obstacles and safety concerns for the user.
    
    Fields:
        event_id: A unique string identifier (e.g. UUID) to track the event life-cycle.
        priority: Emergency hierarchy rating (1 = CRITICAL danger, 2 = Warning, 3 = Informative).
        message: Human-readable alert text (e.g., "Warning: pole directly ahead, 1 meter").
        source_detection: The corresponding Detection object that triggered this hazard.
                          Optional to support systemic alerts (e.g. "System active").
        created_at: Epoch timestamp of when this hazard was generated.
        expires_at: Epoch timestamp indicating when this hazard's relevance ends.
    """
    event_id: str
    priority: int
    message: str
    source_detection: Optional[Detection]
    created_at: float
    expires_at: float

    def to_dict(self) -> dict:
        """
        Converts the HazardEvent to a dictionary. Recursively converts the nested 
        source_detection dataclass into a dictionary if present.
        """
        return asdict(self)

    def to_json(self) -> str:
        """
        Serializes the HazardEvent and all nested attributes into a standard JSON string.
        Highly useful for sending real-time warnings over WebSockets to client apps.
        """
        return json.dumps(self.to_dict())

    def is_expired(self, current_time: Optional[float] = None) -> bool:
        """
        Checks if this safety warning has exceeded its valid lifetime.
        
        Args:
            current_time: Optional epoch timestamp to evaluate against. 
                          Defaults to current system time if not provided.
        """
        t = current_time if current_time is not None else time.time()
        return t >= self.expires_at


@dataclass(slots=True)
class AudioSpeechRequest:
    """
    Structured message contract dispatched to the background voice rendering queue.
    
    Fields:
        message: The exact spoken output text (e.g., "Step down close").
        priority: Urgency index. Audio system prioritizes higher values (lower index numbers).
        cooldown_seconds: The duration for which this exact message should be throttled 
                          to avoid rapid speech stuttering / audio repetition.
        interruptible: If True, this phrase can be cut off mid-speech by an incoming hazard of higher priority.
    """
    message: str
    priority: int
    cooldown_seconds: float
    interruptible: bool

    def to_dict(self) -> dict:
        """
        Converts the AudioSpeechRequest into a clean Python dictionary.
        """
        return asdict(self)


