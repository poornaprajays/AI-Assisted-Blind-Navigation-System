# EXAMPLE USAGE & CONTRACT WORKFLOW DEMONSTRATION
# ================================================================================
if __name__ == "__main__":
    print("--- VisionMate AI Schema Contract Demonstration ---")
    
    # 1. Simulate a frame capture timestamp
    frame_timestamp = time.time()
    
    # 2. Simulate object detector identifying an obstacle (e.g., Chair close ahead)
    # Bounding box represents [xmin, ymin, xmax, ymax]
    bbox_coordinates = (100, 150, 300, 450)
    
    # 3. Instantiate a standardized Detection object
    mock_detection = Detection(
        class_name="chair",
        confidence=0.89,
        bbox=bbox_coordinates,
        center_x=200,             # Pre-calculated: (xmin + xmax) // 2
        center_y=300,             # Pre-calculated: (ymin + ymax) // 2
        width=200,                # Pre-calculated: xmax - xmin
        height=300,               # Pre-calculated: ymax - ymin
        estimated_distance=1.2,   # Distance mapping based on spatial calculations
        spatial_zone="center",    # Bounding box center resides in middle partition
        timestamp=frame_timestamp
    )
    
    print("\n[STEP 1] Detection Created:")
    print(f"  Class: {mock_detection.class_name}")
    print(f"  Confidence: {mock_detection.confidence:.2%}")
    print(f"  Spatial Position: {mock_detection.spatial_zone} zone at {mock_detection.estimated_distance}m")
    
    # 4. Serialize Detection to JSON
    detection_json = mock_detection.to_json()
    print("\n[STEP 2] Serialized Detection JSON:")
    print(f"  {detection_json}")

    # 5. Spatial Logic processes detection and triggers a HazardEvent
    hazard_uuid = "e84a29a0-6c92-491c-8e3b-c2e399583b27"
    current_epoch = time.time()
    valid_lifespan = 1.5  # Hazard is considered active/valid for 1.5 seconds
    
    mock_hazard = HazardEvent(
        event_id=hazard_uuid,
        priority=1,  # Critical priority
        message="Warning: Chair directly ahead, 1.2 meters.",
        source_detection=mock_detection,
        created_at=current_epoch,
        expires_at=current_epoch + valid_lifespan
    )
    
    print("\n[STEP 3] HazardEvent Created:")
    print(f"  Event ID: {mock_hazard.event_id}")
    print(f"  Message: '{mock_hazard.message}'")
    print(f"  Is Expired: {mock_hazard.is_expired()}")
    
    # 6. Serialize HazardEvent (including nested structures) to JSON
    hazard_json = mock_hazard.to_json()
    print("\n[STEP 4] Serialized HazardEvent JSON:")
    # Formatting JSON output nicely for visual terminal display
    parsed_json = json.loads(hazard_json)
    print(json.dumps(parsed_json, indent=2))
    
    # 7. Convert hazard into an Audio speech dispatch request
    mock_speech_req = AudioSpeechRequest(
        message=mock_hazard.message,
        priority=mock_hazard.priority,
        cooldown_seconds=3.0,     # Don't repeat "Chair directly ahead" for at least 3 seconds
        interruptible=True        # Can be overridden if an even worse hazard (e.g. "Step down") is spotted
    )
    
    print("\n[STEP 5] AudioSpeechRequest Dispatched:")
    print(f"  Payload: {mock_speech_req.to_dict()}")
    print("--------------------------------------------------")
